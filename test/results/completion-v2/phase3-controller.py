"""Owner development controller; never supplied as mathematical model context.

All actual author/reviewer/proof stages use the selected isolated carrier.
A shared two-slot budget includes a reservation for the already active PDE
stage. No unperformed semantic judgment is generated by this controller.
"""
from concurrent.futures import ThreadPoolExecutor, as_completed
import datetime
import json
from pathlib import Path
import sys
import threading
import time
import traceback

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'test/support'))
import audit_a_campaign as a
import translation_author as author
import interface_review
import audit_b_mapping
import audit_b_review
from clean_stage import ArtifactStage
import workflow
import run_graph

RESULTS=ROOT/'test/results'
OUT=RESULTS/'completion-v2'
BUDGET=a.concurrency.Budget(a.concurrency.resolve())
LOCK=threading.Lock()
STATES={}
CONTROLS=RESULTS/'audit-a-behavior-v1/behavioral-summary.json'

def update(case,stage,**extra):
    with LOCK:
        STATES[case]={'stage':stage,'updated_at_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),**extra}
        temp=OUT/'phase3-progress.pending';a.write(temp,STATES);temp.replace(OUT/'phase3-progress.json')
        print(case,stage,extra,flush=True)

def accepted(directory):
    row=a.nl0.read_json(directory/'stage/result.json') if hasattr(a.nl0,'read_json') else json.loads((directory/'stage/result.json').read_text())
    if row['status']!='ACCEPTED' or row.get('exposure',{}).get('status')!='TRANSMITTED-EXPOSURE-CHECK-PASSED':
        raise ValueError('No actual exposure-qualified submitted artifact: '+str(directory))
    return row

def translate(case,source,interface_name,workflow_name):
    problem=ROOT/'test'/case
    interface=RESULTS/interface_name
    if not interface.exists():author.prepare(source,problem,interface)
    update(case,'INTERFACE_AUTHORING',directory=str(interface))
    author.run(interface,1800,budget=BUDGET);accepted(interface)
    review=RESULTS/(interface_name+'-review')
    interface_review.prepare(interface,review)
    update(case,'INTERFACE_SEMANTIC_REVIEW',directory=str(review))
    interface_review.run(review,1200,budget=BUDGET)
    checked=interface_review.collect(review)
    if not checked['all_checks_passed']:raise ValueError('Actual interface review did not pass: '+str(review))
    paths=json.loads((interface/'accepted-interface-paths.json').read_text())
    destination=RESULTS/workflow_name
    workflow.freeze(source/'nl0.json',source/'spec.json',paths['contract'],paths['plan'],review/'review.json',destination,
        audit_a=source/'audit-a.json',max_concurrency='auto')
    frozen=workflow.bound(destination)
    update(case,'FROZEN_LEAN_PROOF_WORK',directory=str(destination))
    proof=run_graph.run(Path(frozen['contract']),Path(frozen['plan']),destination/'proof-run',
        timeout_seconds=1800,bank=False,budget=BUDGET)
    workflow.bound(destination)
    if proof['status']!='FRAGMENT_ASSEMBLED':raise ValueError('Actual Lean assembly unfinished: '+str(destination))
    mapping=RESULTS/(workflow_name+'-mapping')
    audit_b_mapping.prepare(destination,mapping)
    update(case,'AUDIT_B_MAPPING_AND_REAL_BUILD',directory=str(mapping))
    audit_b_mapping.run(mapping,1800,budget=BUDGET);audit_b_mapping.adopt(mapping)
    audit_review=RESULTS/(workflow_name+'-audit-b-review')
    audit_b_review.prepare(destination/'audit-b',audit_review)
    update(case,'AUDIT_B_FRESH_SEMANTIC_REVIEW',directory=str(audit_review))
    audit_b_review.run(audit_review,1800,budget=BUDGET)
    verdict=audit_b_review.collect(audit_review)
    if not verdict['all_checks_passed']:raise ValueError('Actual Audit B semantic review did not pass: '+str(audit_review))
    result=workflow.finish(destination,audit_review/'review.json')
    update(case,result['status'],directory=str(destination))
    return result

def source_audit(case,source,name):
    directory=RESULTS/name
    a.prepare(source,ROOT/'test'/case,directory)
    update(case,'AUDIT_A_ACTUAL_REVIEW',directory=str(directory))
    a.run(directory,1200,budget=BUDGET)
    result=a.collect(directory,CONTROLS)
    if not result['full_acceptance']:raise ValueError('Actual Audit A did not pass: '+str(directory))
    a.nl0.render(a.nl0.validate(source/'nl0.json',source/'spec.json'), source/'readable') if False else None
    return result

def existing_wave_reservation():
    # This is a reservation for one already-running real stage, not a new model
    # call. Its own complete interval/usage remains in wave-nl0-v11/stage.
    with BUDGET:
        BUDGET._local.row['external_stage_reservation']='wave-nl0-v11/stage'
        while not (RESULTS/'wave-nl0-v11/stage/result.json').exists():time.sleep(1)
    return {'external_stage_finished':True}

def wave():
    while not (RESULTS/'wave-nl0-v11/stage/result.json').exists():time.sleep(1)
    accepted(RESULTS/'wave-nl0-v11')
    source=RESULTS/'wave-nl0-v11/stage/case'
    source_audit('wave-map-energy',source,'wave-audit-a-v5')
    return translate('wave-map-energy',source,'wave-interface-v1','wave-workflow-v1')

def geometry():
    directory=RESULTS/'geometry-nl0-v9'
    update('geometry-product-dimension','BOUNDED_MEASURE_SOURCE_REPAIR',directory=str(directory))
    stage=ArtifactStage(directory/'stage',(directory/'prompt.txt').read_text(),phase='nl0-authoring',kind='nl0',
        case_id='geometry-product-dimension',inputs=directory/'inputs.json',timeout=1800,budget=BUDGET)
    stage.execute();accepted(directory)
    source=directory/'stage/case'
    source_audit('geometry-product-dimension',source,'geometry-audit-a-v3')
    return translate('geometry-product-dimension',source,'geometry-interface-v1','geometry-workflow-v1')

with ThreadPoolExecutor(max_workers=4) as pool:
    reserved=pool.submit(existing_wave_reservation)
    while BUDGET.report()['active_model_stages']<1:time.sleep(0.01)
    jobs={pool.submit(translate,'lie-module-irreducibility',RESULTS/'lie-nl0-v17/stage/case','lie-interface-v2','lie-workflow-v1'):'lie-module-irreducibility',
          pool.submit(geometry):'geometry-product-dimension',pool.submit(wave):'wave-map-energy'}
    for future in as_completed(jobs):
        case=jobs[future]
        try:future.result()
        except Exception as error:
            text=traceback.format_exc();(OUT/(case+'-phase3-error.txt')).write_text(text)
            update(case,'REPAIR_REQUIRED',error=type(error).__name__+': '+str(error))
    reserved.result()
report=BUDGET.report();report['reservation_note']='The tagged external reservation represents the already-running real PDE author, not an extra model call. Model usage is aggregated only from actual stage result/usage ledgers.'
a.write(OUT/'phase3-concurrency.json',report)
